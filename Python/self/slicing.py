a = "Hello World"
print(a[1:5]) # It prints characters from index 1 to 4
print(a[:5]) # It prints characters from the beginning to index 4
print(a[6:11]) # It prints characters from index 6 to 10
print(a[-5:-1]) # It prints characters from index -5 to -2
print(a[::1]) # It prints the entire string with a step of 1
print(a[::2]) # It prints every second character of the string