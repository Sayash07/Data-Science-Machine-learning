details = (" my name is Sayash Rajak ")
print(details.upper())
print(details.lower())
print(details.strip()) # It removes whitespace from both ends
print(details.lstrip()) # It removes whitespace from the left end
print(details.rstrip()) # It removes whitespace from the right end
print(details.capitalize()) # It capitalizes the first letter of the string
print(details.title()) # It capitalizes the first letter of each word
print(details.startswith("my")) # It checks if the string starts with the given substring   
print(details.endswith("k")) # It checks if the string ends with the given substring
print(details.find("Sayash")) # It returns the index of the first occurrence of the substring
# Once the output is found, it will return the index and end the search 